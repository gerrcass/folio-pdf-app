import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { preview } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const port = 4181;

process.env.VITE_BASE = '/';
process.env.VITE_EDITION = 'web';
execFileSync(process.execPath, [path.join(root, 'scripts', 'copy-pdf-assets.mjs')], { stdio: 'ignore' });
execFileSync(process.execPath, [path.join(root, 'scripts', 'build.mjs'), 'web'], {
  stdio: 'ignore',
  env: process.env,
});

const server = await preview({
  root,
  preview: { port, strictPort: true, host: '127.0.0.1' },
});

const localChromium =
  process.env.PLAYWRIGHT_CHROMIUM_PATH ??
  (fs.existsSync('/usr/bin/chromium-browser') ? '/usr/bin/chromium-browser' : undefined);

const browser = await chromium.launch({
  headless: true,
  executablePath: localChromium,
  args: ['--no-sandbox', '--enable-precise-memory-info'],
});
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
const page = await context.newPage();
const consoleErrors = [];
page.on('console', (message) => {
  if (message.type() === 'error') consoleErrors.push(message.text());
});
page.on('pageerror', (error) => consoleErrors.push(error.message));

await page.goto(`http://127.0.0.1:${port}/`, { waitUntil: 'networkidle' });
await page.waitForSelector('.library-title');

const openStarted = Date.now();
const chooser = page.waitForEvent('filechooser');
await page.getByRole('button', { name: 'Open PDF' }).first().click();
await (await chooser).setFiles(path.join(root, 'tests/fixtures/large.pdf'));
await page.waitForSelector('.reader', { timeout: 60_000 });
await page.waitForFunction(
  () => {
    const canvas = document.querySelector('.page-canvas');
    return Boolean(canvas && canvas.width > 0);
  },
  undefined,
  { timeout: 60_000 },
);
const openMs = Date.now() - openStarted;

const marks = await page.evaluate(() => ({
  measures: performance.getEntriesByType('measure').map((entry) => ({ name: entry.name, duration: entry.duration })),
  heap: performance.memory,
}));

await page.keyboard.press('Control+f');
const searchStarted = Date.now();
const searchInput = page.getByRole('textbox', { name: 'Find in document' });
const fillStarted = Date.now();
await searchInput.fill('luminous margin');
const fillMs = Date.now() - fillStarted;
await page.waitForFunction(
  () => document.querySelector('.search-meta')?.textContent?.includes('5400'),
  undefined,
  { timeout: 120_000 },
);
const searchToCompleteMs = Date.now() - searchStarted;
const firstResultVisibleMs = await page.evaluate(() => {
  const entry = performance.getEntriesByName('folio:index-duration').at(0);
  return entry ? entry.duration : null;
});

const pageStarted = Date.now();
const pageInput = page.locator('.page-input');
await pageInput.fill('150');
await pageInput.press('Enter');
await page.waitForFunction(
  () => {
    const target = document.querySelector('[data-page-index="149"] .page-canvas');
    return Boolean(target && target.width > 0);
  },
  undefined,
  { timeout: 30_000 },
);
const pageJumpMs = Date.now() - pageStarted;
const currentPage = await pageInput.inputValue();
const canvasWidth = await page.locator('.page-canvas').first().evaluate((canvas) => canvas.width);

const result = {
  generatedAt: new Date().toISOString(),
  environment: {
    platform: `${os.platform()} ${os.release()}`,
    cpu: os.cpus()[0]?.model ?? 'unknown',
    cores: os.cpus().length,
    memoryGiB: Math.round((os.totalmem() / 1024 ** 3) * 10) / 10,
    browser: await browser.version(),
    viewport: '1440 × 960',
    fixture: 'tests/fixtures/large.pdf (300 pages, 230 KB)',
  },
  measurements: {
    openToFirstPageMs: openMs,
    searchInputFillMs: fillMs,
    searchToCompleteCountMs: searchToCompleteMs,
    fullIndexMeasureMs: firstResultVisibleMs,
    pageJumpToPage150Ms: pageJumpMs,
    pageAfterJump: currentPage,
    firstCanvasWidth: canvasWidth,
    jsHeapUsedMiB:
      marks.heap && Number.isFinite(marks.heap.usedJSHeapSize)
        ? Math.round((marks.heap.usedJSHeapSize / 1024 ** 2) * 10) / 10
        : null,
  },
  performanceEntries: marks.measures,
  consoleErrors,
};

const markdown = `# Folio performance baseline

Generated by \`npm run bench\`. This is **measured evidence**, not a CI performance gate.

## Environment

- **Generated:** ${result.generatedAt}
- **Platform:** ${result.environment.platform}
- **CPU:** ${result.environment.cpu} (${result.environment.cores} logical cores)
- **Memory:** ${result.environment.memoryGiB} GiB
- **Browser:** ${result.environment.browser}
- **Viewport:** ${result.environment.viewport}
- **Fixture:** ${result.environment.fixture}

## Measurements

| Workflow | Result |
| --- | ---: |
| Open 300-page PDF to painted first page (includes loading, page-layout preparation, and first canvas paint) | ${result.measurements.openToFirstPageMs} ms |
| Search input \`fill\` call while the viewer is live | ${result.measurements.searchInputFillMs} ms |
| Search query to complete 5,400-match count | ${result.measurements.searchToCompleteCountMs} ms |
| Full text-index duration (performance measure, when available) | ${result.measurements.fullIndexMeasureMs === null ? 'not recorded' : `${Math.round(result.measurements.fullIndexMeasureMs)} ms`} |
| Jump from page 1 to page 150 | ${result.measurements.pageJumpToPage150Ms} ms |
| Current page after jump | ${result.measurements.pageAfterJump} |
| Used JS heap after open and indexing | ${result.measurements.jsHeapUsedMiB === null ? 'not exposed' : `${result.measurements.jsHeapUsedMiB} MiB`} |
| Console errors during the run | ${result.consoleErrors.length} |

## What this demonstrates

- The 300-page document can be opened, laid out, and painted without pre-rendering every page.
- Search text extraction and matching complete for 5,400 matches while the page remains interactive and the input can be filled.
- Jumping across the document does not require waiting for all pages to render.

The fixture is generated by \`npm run fixtures\`. Measurements vary with hardware, browser, font loading, and whether the browser has a warm cache. Re-run the script on the target machine before citing a number.
`;

fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'performance.md'), markdown);
console.log(markdown);

await context.close();
await browser.close();
await new Promise((resolve) => server.httpServer.close(resolve));
